// The Replay page in a real browser (Playwright's Chromium) against the real services:
// auth-service, replay-service and the production frontend (:4200). A fresh user
// (replayui_*) logs in through the login page, starts an EUR/USD replay on a real date,
// plays at each speed, places an order with SL and TP and watches it fill and close,
// opens a second tab (OTHER_TAB), closes the tabs while playing and comes back (paused),
// resumes, ends the session and reads the summary. A screenshot per step goes to
// docs/validation/replay-frontend/, the numbers to docs/validation/replay-frontend-e2e.md.
// Every number is read from the page; exits 1 if any check fails.
//
//   npm run replay:browser -- [--start 2022-03-01T09:30Z] [--headed]
import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { chromium, type BrowserContext, type Page } from 'playwright';

const REPO_ROOT = resolve(__dirname, '../../..');
const SHOTS = 'docs/validation/replay-frontend';
const REPORT = 'docs/validation/replay-frontend-e2e.md';
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

const lines: string[] = [];
const failures: string[] = [];
const log = (line = '') => { lines.push(line); console.log(line); };
const check = (ok: boolean, what: string) => { log(`- ${ok ? 'PASS' : '**FAIL**'}: ${what}`); if (!ok) failures.push(what); };
let shot = 0;
async function screenshot(page: Page, name: string, what: string): Promise<void> {
  shot += 1;
  const file = `${String(shot).padStart(2, '0')}-${name}.png`;
  await page.screenshot({ path: join(REPO_ROOT, SHOTS, file) });
  log(`  Screenshot: [\`${file}\`](replay-frontend/${file}) — ${what}`);
}

const text = async (page: Page, testId: string) => (await page.getByTestId(testId).textContent())?.trim() ?? '';
const clockOf = (page: Page) => text(page, 'replay-clock');
const statusOf = (page: Page) => text(page, 'replay-status');
async function waitForText(page: Page, testId: string, expected: string | RegExp, timeoutMs = 15_000): Promise<string> {
  const until = Date.now() + timeoutMs;
  let last = '';
  while (Date.now() < until) {
    last = await text(page, testId).catch(() => '');
    if (typeof expected === 'string' ? last === expected : expected.test(last)) return last;
    await sleep(50);
  }
  throw new Error(`${testId}: expected ${expected}, last "${last}"`);
}

// Plays at one speed and measures the gaps between clock changes seen in the page
async function playAt(page: Page, label: string, bars: number): Promise<{ meanMs: number; changes: number }> {
  await page.getByRole('button', { name: label, exact: true }).click();
  await page.getByRole('button', { name: label, exact: true, pressed: true }).waitFor();
  await page.getByTestId('replay-play').click();
  await waitForText(page, 'replay-status', 'Playing');
  const seen: number[] = [];
  let previous = await clockOf(page);
  while (seen.length < bars + 1) {
    const now = await clockOf(page);
    if (now !== previous) { seen.push(Date.now()); previous = now; }
    await sleep(10);
  }
  await page.getByTestId('replay-play').click();
  await waitForText(page, 'replay-status', 'Paused');
  const gaps = seen.slice(1).map((t, i) => t - seen[i]);
  return { meanMs: Math.round(gaps.reduce((a, b) => a + b, 0) / gaps.length), changes: gaps.length };
}

async function openReplay(context: BrowserContext, frontend: string): Promise<Page> {
  const page = await context.newPage();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${frontend}/replay`);
  return page;
}

async function main(): Promise<void> {
  process.loadEnvFile(join(REPO_ROOT, '.env'));
  const argv = process.argv.slice(2);
  const arg = (flag: string, fallback: string) => (argv.indexOf(flag) >= 0 ? argv[argv.indexOf(flag) + 1] : fallback);
  const start = arg('--start', '2022-03-01T09:30Z');
  const authUrl = process.env['VERIFY_AUTH_URL'] ?? 'http://localhost:3000/api';
  const frontend = process.env['VERIFY_FRONTEND_URL'] ?? 'http://localhost:4200';
  mkdirSync(join(REPO_ROOT, SHOTS), { recursive: true });

  const id = randomBytes(4).toString('hex');
  const email = `replayui_${id}@example.com`;
  const password = `Ui@${randomBytes(6).toString('hex')}1A`;
  const reg = await fetch(`${authUrl}/auth/register`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email, username: `rui_${id}`, password, firstName: 'Replay', lastName: 'Browser' }),
  });
  if (!reg.ok) throw new Error(`register: HTTP ${reg.status} ${await reg.text()}`);

  log('# Replay page browser run (step 6b-2)');
  log();
  log(`Generated by \`npm run replay:browser\` on ${new Date().toISOString()} at commit ` +
    `\`${execSync('git rev-parse --short HEAD', { cwd: REPO_ROOT }).toString().trim()}\`, user \`${email}\`, in Playwright's ` +
    'Chromium against the running auth-service, replay-service and production frontend, on the imported Dukascopy history. ' +
    'Every value below is read from the page.');
  log();

  const browser = await chromium.launch({ headless: !argv.includes('--headed') });
  const context = await browser.newContext();
  try {
    // ── 1. Log in and start ──
    log('## 1. Start a session');
    const login = await context.newPage();
    await login.setViewportSize({ width: 1440, height: 900 });
    await login.goto(`${frontend}/login`);
    await login.getByPlaceholder('trader@example.com').fill(email);
    await login.getByPlaceholder('••••••••').fill(password);
    await login.getByRole('button', { name: /sign in|log in/i }).click();
    await login.waitForURL('**/dashboard');
    await login.goto(`${frontend}/replay`);
    const page = login;
    await page.getByTestId('replay-start-form').waitFor();
    await page.getByLabel('Pair').selectOption('EUR_USD');
    await page.getByLabel('Start date (UTC)').fill(start.slice(0, 10));
    await page.getByLabel('Start time (UTC)').fill(start.slice(11, 16));
    await page.getByLabel('Chart timeframe').selectOption('1m');
    await screenshot(page, 'start-form', `the start form: EUR/USD, ${start}, $10,000, 1m`);
    await page.getByRole('button', { name: 'Start replay' }).click();
    await page.getByTestId('replay-badge').waitFor();
    const opened = await clockOf(page);
    log(`Opened: badge "${await text(page, 'replay-badge')}", "${opened}", status "${await statusOf(page)}", ` +
      `bid ${await text(page, 'replay-bid')} / ask ${await text(page, 'replay-ask')}`);
    check(opened === `Replay time: ${start.slice(0, 10)} ${start.slice(11, 16)} UTC`, 'the session opens on the start minute');
    check(await statusOf(page) === 'Paused', 'it opens paused');
    await screenshot(page, 'session-open', 'the replay screen, paused, with the REPLAY badge and the replay clock');

    // ── 2. Speeds ──
    log();
    log('## 2. Play at each speed (1m bars, 6 clock changes each)');
    log('| Speed | Mean gap between clock changes (ms) | Changes |');
    log('|---|---|---|');
    const speeds: [string, number][] = [['2 s', 2000], ['1 s', 1000], ['0.5 s', 500]];
    for (const [label, ms] of speeds) {
      const r = await playAt(page, label, 6);
      log(`| ${label} | ${r.meanMs} | ${r.changes} |`);
      check(Math.abs(r.meanMs - ms) <= ms * 0.25, `${label}: a bar about every ${ms} ms (${r.meanMs})`);
    }
    await screenshot(page, 'after-playing', 'paused after playing at 2 s, 1 s and 0.5 s');

    // ── 3. Order with SL and TP ──
    log();
    log('## 3. Market order with SL and TP');
    const bid = await text(page, 'replay-bid');
    const ask = await text(page, 'replay-ask');
    const at = await clockOf(page);
    const points = Math.round(Number(bid) * 1e5);
    const sl = ((points - 100) / 1e5).toFixed(5);
    const tp = ((points + 100) / 1e5).toFixed(5);
    await page.getByLabel('Stop loss').fill(sl);
    await page.getByLabel('Take profit').fill(tp);
    await page.getByRole('button', { name: 'Buy 0.10 lots' }).click();
    const row = page.getByTestId('replay-position-row').first();
    await row.waitFor();
    const pendingStatus = (await row.locator('td').first().textContent())?.trim();
    log(`${at}: bid ${bid}, ask ${ask}; BUY 0.10 lots, SL ${sl}, TP ${tp} -> "${pendingStatus}"`);
    check(pendingStatus === "Pending · fills at the next minute's open", 'the order is pending until the next minute');
    await screenshot(page, 'order-pending', 'the order, pending with Cancel');
    await page.getByTestId('replay-step').click();
    await row.locator('td').first().filter({ hasText: /^Open$/ }).waitFor();
    const cells = (await row.locator('td').allTextContents()).map((c) => c.trim());
    log(`After one step (${await clockOf(page)}): ${cells.slice(0, 7).join(' | ')}`);
    check(cells[0] === 'Open' && /^\d\.\d{5}$/.test(cells[3]), `filled at the next minute's open (entry ${cells[3]})`);
    await screenshot(page, 'order-filled', 'the position open, with its live P&L');

    await page.getByRole('button', { name: '0.5 s', exact: true }).click();
    await page.getByTestId('replay-play').click();
    await page.getByRole('tab', { name: /Closed trades/ }).click();
    await page.getByTestId('replay-closed-row').first().waitFor({ timeout: 180_000 });
    await page.getByTestId('replay-play').click();
    await waitForText(page, 'replay-status', 'Paused');
    const closed = (await page.getByTestId('replay-closed-row').first().locator('td').allTextContents()).map((c) => c.trim());
    log(`Closed: ${closed.join(' | ')}`);
    check(['Stop loss', 'Take profit'].includes(closed[4]), `closed by its ${closed[4]}`);
    const account = await page.getByTestId('replay-account').locator('dd').allTextContents();
    log(`Account: balance ${account[0]}, equity ${account[1]}, unrealised ${account[2]}, margin used ${account[3]}, free margin ${account[4]}`);
    await screenshot(page, 'trade-closed', 'the trade in Closed trades and the account after it');

    // ── 4. A second tab ──
    log();
    log('## 4. A second tab while playing');
    await page.getByTestId('replay-play').click();
    await waitForText(page, 'replay-status', 'Playing');
    const second = await openReplay(context, frontend);
    await second.getByTestId('replay-resume-card').waitFor();
    const firstStatus = await waitForText(page, 'replay-status', 'Paused: replay opened in another tab or window');
    log(`First tab: "${firstStatus}"; second tab: the resume card`);
    check(firstStatus === 'Paused: replay opened in another tab or window', 'the first tab shows the OTHER_TAB message');
    await screenshot(page, 'other-tab-first', 'the first tab after the second one opened');
    await screenshot(second, 'other-tab-second', 'the second tab: the resume card');
    await second.close();

    // ── 5. Close while playing, come back ──
    log();
    log('## 5. Close the tab while playing and come back');
    await page.getByTestId('replay-play').click();
    await waitForText(page, 'replay-status', 'Playing');
    await sleep(1_200);
    await page.close();
    await sleep(2_000);
    const back = await openReplay(context, frontend);
    const card = back.getByTestId('replay-resume-card');
    await card.waitFor();
    const cardValues = await card.locator('dd').allTextContents();
    log(`Resume card: ${cardValues.join(' | ')}`);
    await screenshot(back, 'resume-card', 'back on /replay: the resume card');
    await sleep(2_000);
    const cardAgain = await card.locator('dd').allTextContents();
    check(cardAgain[1] === cardValues[1], `the clock did not move while away (${cardValues[1]})`);
    await back.getByRole('button', { name: 'Resume' }).click();
    const backStatus = await waitForText(back, 'replay-status', /^Paused/);
    log(`Resumed: "${backStatus}", ${await clockOf(back)}`);
    check(backStatus === 'Paused: connection lost', 'resumed paused, with the DISCONNECT message');
    await screenshot(back, 'resumed', 'the session resumed, paused');

    // ── 6. End ──
    log();
    log('## 6. End the session');
    await back.getByRole('button', { name: 'End session' }).click();
    const confirmText = (await back.getByTestId('replay-end-confirm').locator('p').first().textContent())?.trim();
    log(`Confirmation: "${confirmText}"`);
    await screenshot(back, 'end-confirm', 'the confirmation on the page');
    await back.getByRole('button', { name: 'Yes, end the session' }).click();
    await back.getByTestId('replay-summary').waitFor();
    const summary = {
      balance: await text(back, 'replay-summary-balance'),
      pnl: await text(back, 'replay-summary-pnl'),
      trades: await text(back, 'replay-summary-trades'),
    };
    log(`Summary: balance ${summary.balance}, net P&L ${summary.pnl}, trades ${summary.trades}`);
    check(summary.trades === '1', 'one trade');
    check(summary.pnl === closed[5], `net P&L equals the closed trade's (${closed[5]})`);
    await screenshot(back, 'summary', 'the summary');
    await back.getByRole('button', { name: 'New replay' }).click();
    check(await back.getByTestId('replay-start-form').isVisible(), 'back to the start form');
  } finally {
    await browser.close();
  }

  log();
  log(`**Result: ${failures.length === 0 ? 'all checks pass' : `${failures.length} check(s) failed`}.**`);
  writeFileSync(join(REPO_ROOT, REPORT), `${lines.join('\n')}\n`);
  if (failures.length > 0) process.exit(1);
}

main().then(() => process.exit(0), (err) => { console.error(err); process.exit(1); });
