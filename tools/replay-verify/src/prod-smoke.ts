// The production stack on one machine (item 13 of step 7): docker-compose.prod.yml behind Caddy, driven
// in Playwright's Chromium and over HTTPS like a visitor, on the history imported with data:transfer.
//
//   1. the front door: HTTP -> HTTPS, www -> apex, /health and unknown /api paths 404 from outside
//   2. registration closed (API 403, no Register link), the demo user logs in, terminal dot "No live feed"
//   3. a backtest through the page, its results.json through Caddy (ws-gateway reads the store)
//   4. replay: start, play, one order that fills at the next minute's open, end
//   5. memory: docker stats idle and while the replay plays, Redis used_memory, total vs 3.5 GB
//
// Every value is read from the page, the API or Docker; exits 1 if a check fails. Report:
// docs/validation/prod-local-run.md, screenshots in docs/validation/prod-local/.
//
//   VERIFY_EMAIL=... VERIFY_PASSWORD=... npm run prod:smoke -- [--base https://localhost] [--headed]
// (the demo user from infra/.env.demo-users; Caddy's local CA is accepted for localhost only)
import { execFileSync, execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { chromium, type Page } from 'playwright';

const REPO_ROOT = resolve(__dirname, '../../..');
const SHOTS = 'docs/validation/prod-local';
const REPORT = 'docs/validation/prod-local-run.md';
const PROJECT = 'forexedge'; // compose project name (docker-compose.prod.yml)
const BUDGET_MB = 3.5 * 1024;
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

const lines: string[] = [];
const failures: string[] = [];
const log = (line = '') => { lines.push(line); console.log(line); };
const check = (ok: boolean, what: string) => { log(`- ${ok ? 'PASS' : '**FAIL**'}: ${what}`); if (!ok) failures.push(what); };
let shot = 0;
async function screenshot(page: Page, name: string, what: string): Promise<void> {
  shot += 1;
  const file = `${String(shot).padStart(2, '0')}-${name}.png`;
  await page.screenshot({ path: join(REPO_ROOT, SHOTS, file) });
  log(`  Screenshot: [\`${file}\`](prod-local/${file}) — ${what}`);
}

// ── Docker measurements ──
interface MemRow { name: string; usedMb: number; limitMb: number }
const toMb = (s: string) => {
  const m = /^([\d.]+)\s*([KMG]i?B|B)$/.exec(s.trim());
  if (!m) return NaN;
  const unit = m[2][0];
  return Number(m[1]) * (unit === 'G' ? 1024 : unit === 'M' ? 1 : unit === 'K' ? 1 / 1024 : 1 / 1048576);
};
function dockerStats(): MemRow[] {
  const out = execFileSync('docker', ['stats', '--no-stream', '--format', '{{.Name}}|{{.MemUsage}}'], { encoding: 'utf8' });
  return out.split('\n').filter((l) => l.startsWith(`${PROJECT}-`)).map((l) => {
    const [name, usage] = l.split('|');
    const [used, limit] = usage.split('/');
    return { name: name.replace(`${PROJECT}-`, '').replace(/-1$/, ''), usedMb: toMb(used), limitMb: toMb(limit) };
  }).sort((a, b) => a.name.localeCompare(b.name));
}
function redisUsedMemory(): string {
  const pass = execFileSync('docker', ['exec', `${PROJECT}-redis-1`, 'printenv', 'REDIS_PASS'], { encoding: 'utf8' }).trim();
  const info = execFileSync('docker', ['exec', `${PROJECT}-redis-1`, 'redis-cli', '-a', pass, '--no-auth-warning', 'INFO', 'memory'],
    { encoding: 'utf8' });
  const field = (k: string) => new RegExp(`^${k}:(.*)$`, 'm').exec(info)?.[1].trim() ?? '?';
  return `used_memory ${field('used_memory_human')} (peak ${field('used_memory_peak_human')}, maxmemory ${field('maxmemory_human')})`;
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const base = (argv.indexOf('--base') >= 0 ? argv[argv.indexOf('--base') + 1] : 'https://localhost').replace(/\/$/, '');
  const host = new URL(base).hostname;
  const email = process.env['VERIFY_EMAIL'];
  const password = process.env['VERIFY_PASSWORD'];
  if (!email || !password) throw new Error('set VERIFY_EMAIL and VERIFY_PASSWORD (the demo user)');
  // Caddy's local CA signs https://localhost; anywhere else the certificate must verify
  if (host === 'localhost') process.env['NODE_TLS_REJECT_UNAUTHORIZED'] = '0';
  mkdirSync(join(REPO_ROOT, SHOTS), { recursive: true });

  log('# Production stack on one machine (step 7, item 13)');
  log();
  log(`Generated by \`npm run prod:smoke\` on ${new Date().toISOString()} at commit ` +
    `\`${execSync('git rev-parse --short HEAD', { cwd: REPO_ROOT }).toString().trim()}\` against ${base}: ` +
    '`infra/docker-compose.prod.yml` + `docker-compose.local.yml` (MinIO instead of S3), the history imported with ' +
    '`npm run data:transfer`. Every value below is read from the page, the API or Docker.');
  log();

  const idle = dockerStats();
  check(idle.length >= 13, `${idle.length} containers of the stack are running`);

  // ── 1. Front door ──
  log('## 1. The front door (Caddy)');
  const plain = await fetch(base.replace('https://', 'http://') + '/login', { redirect: 'manual' });
  check([301, 308].includes(plain.status) && (plain.headers.get('location') ?? '').startsWith('https://'),
    `HTTP redirects to HTTPS (${plain.status} -> ${plain.headers.get('location')})`);
  const www = await fetch(`https://www.${host}/replay?x=1`, { redirect: 'manual' });
  check(www.status === 301 && www.headers.get('location') === `https://${host}/replay?x=1`,
    `www redirects to the apex (${www.status} -> ${www.headers.get('location')})`);
  // every prefix reaches its own service: a public route's 200, or that service's JWT guard (401)
  const routes: [string, number, string][] = [
    ['/api/auth/config', 200, 'auth-service'], ['/api/market/feed/status', 200, 'market-service'],
    ['/api/domain/sessions/current', 200, 'domain-service'], ['/api/orders', 401, 'order-service'],
    ['/api/positions', 401, 'order-service'], ['/api/account/summary', 401, 'order-service'],
    ['/api/backtest', 401, 'ws-gateway'], ['/api/ml/health', 200, 'ml-service'],
    ['/api/research/health', 200, 'research-agent'], ['/api/replay/sessions/active', 401, 'replay-service'],
    ['/replay', 200, 'frontend'],
  ];
  for (const [path, status, service] of routes) {
    const r = await fetch(base + path);
    check(r.status === status, `${path} reaches ${service} (${r.status})`);
  }
  const sock = await fetch(`${base}/socket.io/?EIO=4&transport=polling`);
  const replaySock = await fetch(`${base}/api/replay/socket.io/?EIO=4&transport=polling`);
  check(sock.status === 200 && replaySock.status === 200,
    `both Socket.IO paths answer (/socket.io ${sock.status}, /api/replay/socket.io ${replaySock.status})`);
  for (const path of ['/health/live', '/health/ready', '/admin/queues', '/api/nothing-here']) {
    const r = await fetch(base + path);
    check(r.status === 404, `${path} is not reachable from outside (${r.status})`);
  }
  const hsts = (await fetch(base + '/login')).headers.get('strict-transport-security');
  check(!!hsts, `HSTS header (${hsts})`);

  // ── 2. Registration, login, terminal ──
  log();
  log('## 2. Registration closed, demo login, terminal');
  const reg = await fetch(`${base}/api/auth/register`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'smoke@example.com', username: 'smoke_user', password: 'Smoke!Passw0rd1', firstName: 'S', lastName: 'U' }),
  });
  check(reg.status === 403, `POST /api/auth/register is refused (${reg.status})`);
  // An API token for reading results later, taken BEFORE the browser logs in: auth-service keeps one
  // refresh token per user, so a later login would end the browser's session at its next page load.
  const token = (await (await fetch(`${base}/api/auth/login`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password }),
  })).json() as { accessToken: string }).accessToken;
  check(typeof token === 'string' && token.length > 0, 'the demo user logs in over the API');

  // Docker Desktop resets IPv6 connections to published ports, and Chromium tries ::1 first for localhost
  const browser = await chromium.launch({
    headless: !argv.includes('--headed'),
    args: host === 'localhost' ? ['--host-resolver-rules=MAP localhost 127.0.0.1'] : [],
  });
  const context = await browser.newContext({ ignoreHTTPSErrors: host === 'localhost' });
  const page = await context.newPage();
  await page.setViewportSize({ width: 1440, height: 900 });
  try {
    await page.goto(`${base}/login`);
    await page.getByPlaceholder('trader@example.com').waitFor();
    await sleep(1_000); // the config query settles
    check(await page.getByRole('link', { name: 'Create one' }).count() === 0, 'no Register link on the login page');
    await page.getByPlaceholder('trader@example.com').fill(email);
    await page.getByPlaceholder('••••••••').fill(password);
    await page.getByRole('button', { name: /sign in/i }).click();
    await page.waitForURL('**/dashboard');
    const dot = page.getByTestId('live-indicator');
    await dot.filter({ hasText: /^No live feed$/ }).waitFor({ timeout: 20_000 }).catch(() => undefined);
    const dotText = (await dot.textContent())?.trim();
    check(dotText === 'No live feed' && (await dot.getAttribute('data-tone')) === 'grey',
      `terminal status dot: "${dotText}" (MARKET_FEED=none; ws-gateway's socket through Caddy)`);
    await screenshot(page, 'terminal', 'the terminal after login: "No live feed"');

    // ── 3. Backtest ──
    log();
    log('## 3. Backtest');
    type Run = { id: string; status: string; totalTrades: number | string | null };
    const auth = { headers: { Authorization: `Bearer ${token}` } };
    const listRuns = async () => await (await fetch(`${base}/api/backtest`, auth)).json() as Run[];
    const before = new Set((await listRuns()).map((r) => r.id));
    await page.goto(`${base}/backtest`);
    await page.locator('select[name="instrument"]').selectOption('EUR_USD');
    await page.locator('input[name="from"]').fill('2022-01-03');
    await page.locator('input[name="to"]').fill('2022-01-31');
    await page.getByRole('button', { name: 'Run backtest' }).click();
    // the run this page just submitted (earlier runs stay in the list)
    let run: Run | undefined;
    for (const until = Date.now() + 180_000; Date.now() < until; await sleep(1_000)) {
      run = (await listRuns()).find((r) => !before.has(r.id));
      if (run && ['COMPLETED', 'FAILED'].includes(run.status)) break;
    }
    check(run?.status === 'COMPLETED', `the submitted backtest completed (${run?.id}: ${run?.status})`);
    await page.reload();
    const row = page.locator('tbody tr', { hasText: 'COMPLETED' }).first();
    await row.waitFor();
    log(`Run: ${(await row.locator('td').allTextContents()).map((c) => c.trim()).slice(0, 5).join(' | ')}`);
    await row.click();
    await screenshot(page, 'backtest', 'the completed run with its metrics');

    const results = await fetch(`${base}/api/backtest/${run?.id}/results`, auth);
    const body = await results.json() as { trades?: unknown[] };
    log(`GET /api/backtest/${run?.id}/results: ${results.status}, ${results.headers.get('content-type')}, ` +
      `${body.trades?.length} trades (the run says ${run?.totalTrades})`);
    check(results.status === 200 && Array.isArray(body.trades) && body.trades.length === Number(run?.totalTrades) &&
      body.trades.length > 0, 'results.json comes back through Caddy from the store, with the run\'s trades');

    // ── 4. Replay ──
    log();
    log('## 4. Replay: play and one order');
    await page.goto(`${base}/replay`);
    const resume = page.getByTestId('replay-resume-card');
    if (await resume.isVisible().catch(() => false)) {
      await page.getByRole('button', { name: 'End session' }).click();
      await page.getByRole('button', { name: 'Yes, end the session' }).click();
    }
    await page.getByTestId('replay-start-form').waitFor();
    await page.getByLabel('Pair').selectOption('EUR_USD');
    await page.getByLabel('Start date (UTC)').fill('2022-03-01');
    await page.getByLabel('Start time (UTC)').fill('09:30');
    await page.getByLabel('Chart timeframe').selectOption('1m');
    await page.getByRole('button', { name: 'Start replay' }).click();
    await page.getByTestId('replay-badge').waitFor();
    const opened = (await page.getByTestId('replay-clock').textContent())?.trim();
    check(opened === 'Replay time: 2022-03-01 09:30 UTC', `the session opens on its start minute (${opened})`);
    await page.getByRole('button', { name: '0.5 s', exact: true }).click();
    await page.getByTestId('replay-play').click();
    await page.getByTestId('replay-status').filter({ hasText: /^Playing$/ }).waitFor();
    await sleep(4_000);
    const playing = dockerStats();
    const redis = redisUsedMemory();
    const clockBefore = (await page.getByTestId('replay-clock').textContent())?.trim();
    await sleep(2_000);
    const clockAfter = (await page.getByTestId('replay-clock').textContent())?.trim();
    check(clockBefore !== clockAfter, `the replay plays (${clockBefore} -> ${clockAfter}; socket /api/replay/socket.io through Caddy)`);
    await page.getByTestId('replay-play').click();
    await page.getByTestId('replay-status').filter({ hasText: /^Paused$/ }).waitFor();

    const bid = (await page.getByTestId('replay-bid').textContent())?.trim();
    const ask = (await page.getByTestId('replay-ask').textContent())?.trim();
    const at = (await page.getByTestId('replay-clock').textContent())?.trim();
    await page.getByRole('button', { name: 'Buy 0.10 lots' }).click();
    const position = page.getByTestId('replay-position-row').first();
    await position.waitFor();
    const pending = (await position.locator('td').first().textContent())?.trim();
    check(pending === "Pending · fills at the next minute's open", `${at}: BUY 0.10 at bid ${bid} / ask ${ask} is pending`);
    await page.getByTestId('replay-step').click();
    await position.locator('td').first().filter({ hasText: /^Open$/ }).waitFor();
    const filled = (await position.locator('td').allTextContents()).map((c) => c.trim());
    log(`After one step (${(await page.getByTestId('replay-clock').textContent())?.trim()}): ${filled.slice(0, 7).join(' | ')}`);
    check(filled[0] === 'Open' && /^\d\.\d{5}$/.test(filled[3]), `filled at the next minute's open (entry ${filled[3]})`);
    await screenshot(page, 'replay-order', 'the replay with the filled order');
    await page.getByRole('button', { name: 'End session' }).click();
    await page.getByRole('button', { name: 'Yes, end the session' }).click();
    await page.getByTestId('replay-summary').waitFor();
    check(true, 'the session ended with a summary');

    // ── 5. Memory ──
    log();
    log('## 5. Memory (docker stats)');
    log('| Container | Idle (MB) | Replay playing (MB) | Limit (MB) |');
    log('|---|---|---|---|');
    const byName = new Map(playing.map((r) => [r.name, r]));
    for (const r of idle) {
      log(`| ${r.name} | ${r.usedMb.toFixed(0)} | ${(byName.get(r.name)?.usedMb ?? NaN).toFixed(0)} | ${r.limitMb.toFixed(0)} |`);
    }
    const idleTotal = idle.reduce((n, r) => n + r.usedMb, 0);
    const playTotal = playing.reduce((n, r) => n + r.usedMb, 0);
    log(`| **Total** | **${idleTotal.toFixed(0)}** | **${playTotal.toFixed(0)}** | ${idle.reduce((n, r) => n + r.limitMb, 0).toFixed(0)} |`);
    log();
    log(`Redis (during play): ${redis}`);
    check(playTotal < BUDGET_MB, `total while the replay plays ${playTotal.toFixed(0)} MB < ${BUDGET_MB} MB`);
    for (const r of playing) check(r.usedMb < r.limitMb, `${r.name} below its limit (${r.usedMb.toFixed(0)} / ${r.limitMb.toFixed(0)} MB)`);
  } finally {
    await browser.close();
  }

  log();
  log(failures.length ? `**${failures.length} check(s) failed.**` : 'All checks pass.');
  writeFileSync(join(REPO_ROOT, REPORT), lines.join('\n') + '\n');
  if (failures.length) process.exit(1);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.stack : err);
  process.exit(1);
});
