// End-to-end run of the replay backend (step 6b-1) against the real services
// (auth-service and replay-service running) and the real history: a fresh user
// creates an EUR/USD session on a real date, plays at each speed, places a market
// order with SL and TP, plays until it closes, disconnects while playing and
// reconnects (paused, nothing plays), and ends the session. Every number in the report
// comes from the API; the fill and close money is recomputed here from the reported
// prices (points x units / 10^5, 0.7 pip commission per side) and must agree.
// Writes docs/validation/replay-backend-e2e.md; exits 1 if any check fails.
//
//   npm run replay:e2e -- [--start 2022-03-01T09:30Z] [--report docs/validation/replay-backend-e2e.md]
import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { io, Socket } from 'socket.io-client';

const REPO_ROOT = resolve(__dirname, '../../..');
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

interface Position {
  id: string; side: string; status: string; units: number; entryTime: string | null; entryPrice: string | null;
  stopLoss: string | null; takeProfit: string | null; exitTime: string | null; exitPrice: string | null;
  exitReason: string | null; realizedPnlUsd: string | null; marginUsd: string; placedAt: string;
}

// The API's views, as far as this run reads them
interface Session { id: string; status: string; clockTime: string; balance: string }
interface Bar { time: string; lastMinute: string | null; bid: { close: string }; ask: { close: string } }
interface State { session: Session; bars: Bar[]; currentBar: Bar }
interface Account { equity: string; freeMargin: string }
interface Ended { session: Session; closed: Position[]; cancelled: Position[] }
interface Ack { ok: boolean; error?: string }
interface Received { event: string; payload: unknown; at: number }
const barOf = (e: Received) => e.payload as { bar: Bar; clockTime: string };

const lines: string[] = [];
const failures: string[] = [];
const log = (line: string) => { lines.push(line); console.log(line); };
const check = (ok: boolean, what: string) => { log(`- ${ok ? 'PASS' : '**FAIL**'}: ${what}`); if (!ok) failures.push(what); };

async function main(): Promise<void> {
  process.loadEnvFile(join(REPO_ROOT, '.env'));
  const argv = process.argv.slice(2);
  const arg = (flag: string, fallback: string) => (argv.indexOf(flag) >= 0 ? argv[argv.indexOf(flag) + 1] : fallback);
  const start = arg('--start', '2022-03-01T09:30Z');
  const reportPath = resolve(REPO_ROOT, arg('--report', 'docs/validation/replay-backend-e2e.md'));
  const authUrl = process.env['VERIFY_AUTH_URL'] ?? 'http://localhost:3000/api';
  const replayUrl = process.env['VERIFY_REPLAY_URL'] ?? 'http://localhost:3008';

  const id = randomBytes(4).toString('hex');
  const reg = await fetch(`${authUrl}/auth/register`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: `replaye2e_${id}@example.com`, username: `re2e_${id}`,
      password: `E2e@${randomBytes(6).toString('hex')}1A`, firstName: 'Replay', lastName: 'E2e' }),
  });
  if (!reg.ok) throw new Error(`register: HTTP ${reg.status} ${await reg.text()}`);
  const { accessToken: token } = (await reg.json()) as { accessToken: string };
  const rest = async <T>(method: string, path: string, body?: unknown) => {
    const r = await fetch(`${replayUrl}/api/replay${path}`, {
      method, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    return { status: r.status, body: (await r.json()) as T };
  };
  const connect = async () => {
    const socket: Socket = io(`${replayUrl}/replay`, { path: '/api/replay/socket.io', auth: { token }, transports: ['websocket'], reconnection: false });
    const events: Received[] = [];
    socket.onAny((event: string, payload: unknown) => events.push({ event, payload, at: Date.now() }));
    const state = await new Promise<State>((ok, fail) => { socket.once('state', ok); socket.once('connect_error', fail); });
    // every command names the session the socket was given
    const ack = (cmd: string, body?: object) => new Promise<Ack>((ok) => socket.emit(cmd, { sessionId: state.session.id, ...body }, ok));
    return { socket, events, state, ack };
  };

  log('# Replay backend end-to-end run (step 6b-1)');
  log('');
  log(`Generated by \`npm run replay:e2e\` on ${new Date().toISOString()} at commit ` +
    `\`${execSync('git rev-parse --short HEAD', { cwd: REPO_ROOT }).toString().trim()}\`, user \`replaye2e_${id}@example.com\`, ` +
    'against the running auth-service and replay-service and the imported Dukascopy history.');
  log('');

  log('## 1. Create a session');
  const created = await rest<Session>('POST', '/sessions', { instrument: 'EUR_USD', startTime: start, timeframe: '1m' });
  log(`POST /sessions {EUR_USD, ${start}, 1m}: HTTP ${created.status}, clock ${created.body.clockTime}, status ` +
    `${created.body.status}, balance ${created.body.balance}`);
  check(created.status === 201 && created.body.status === 'PAUSED', 'created PAUSED');
  const again = await rest<Session>('POST', '/sessions', { instrument: 'XAU_USD', startTime: start, timeframe: '1h' });
  check(again.status === 201 && (await rest<Session>('GET', '/sessions/active')).body.id === again.body.id,
    `a second create is 201 and the current session (HTTP ${again.status})`);
  check((await rest<Session>('POST', `/sessions/${again.body.id}/end`)).status === 200, 'the second session ends by its id');
  const reopened = await rest<{ session: Session }>('POST', `/sessions/${created.body.id}/open`);
  check(reopened.status === 200 && reopened.body.session.id === created.body.id && reopened.body.session.status === 'PAUSED',
    'opening the first session again: it is current and PAUSED');

  let c = await connect();
  log(`Socket state on connect: ${c.state.session.status}, clock ${c.state.session.clockTime}, ${c.state.bars.length} history bars, ` +
    `current bar ${c.state.currentBar.time} (last minute ${c.state.currentBar.lastMinute}), bid/ask close ` +
    `${c.state.currentBar.bid.close}/${c.state.currentBar.ask.close}`);
  log('');

  log('## 2. Play at each speed (4 bars each, 1m)');
  log('| Speed | Bars | Gaps between bars (ms) | Mean gap | Clock after |');
  log('|---|---|---|---|---|');
  const paces: [number, number][] = [];
  for (const speedMs of [2000, 1000, 500]) {
    const set = await c.ack('setSpeed', { speedMs });
    if (!set.ok) throw new Error(`setSpeed ${speedMs}: ${set.error}`);
    const from = c.events.length;
    await c.ack('play');
    for (const until = Date.now() + speedMs * 6; c.events.slice(from).filter((e) => e.event === 'bar').length < 4 && Date.now() < until;) {
      await sleep(25);
    }
    await c.ack('pause');
    const bars = c.events.slice(from).filter((e) => e.event === 'bar');
    const gaps = bars.slice(1).map((b, i) => b.at - bars[i].at);
    const mean = gaps.reduce((s, g) => s + g, 0) / gaps.length;
    paces.push([speedMs, mean]);
    log(`| ${speedMs} ms | ${bars.length} | ${gaps.join(', ')} | ${Math.round(mean)} | ${bars.length > 0 ? barOf(bars[bars.length - 1]).clockTime : '-'} |`);
  }
  log('');
  for (const [speedMs, mean] of paces) check(Math.abs(mean - speedMs) <= speedMs * 0.25, `${speedMs} ms per bar: mean gap ${Math.round(mean)} ms (within 25%)`);
  for (const bad of [750, '1000', 0.5]) {
    const r = await c.ack('setSpeed', { speedMs: bad });
    check(!r.ok, `setSpeed ${JSON.stringify(bad)} refused: ${r.error}`);
  }
  log('');

  log('## 3. A market order with SL and TP, played until it closes');
  const st = await rest<Session>('GET', '/sessions/active');
  const played = c.events.filter((e) => e.event === 'bar');
  const lastBar = barOf(played[played.length - 1]).bar;
  const bid = Number(lastBar.bid.close);
  const sl = Number((bid - 0.0010).toFixed(5));
  const tp = Number((bid + 0.0010).toFixed(5));
  log(`Clock ${st.body.clockTime}, bid close ${lastBar.bid.close}: BUY 0.1 lot, SL ${sl.toFixed(5)}, TP ${tp.toFixed(5)}`);
  const placed = await rest<{ position: Position; account: Account }>('POST', `/sessions/${created.body.id}/orders`, { side: 'BUY', lots: 0.1, stopLoss: sl, takeProfit: tp });
  log(`POST /orders: HTTP ${placed.status}, ${placed.body.position.status}, placed at ${placed.body.position.placedAt}, margin ` +
    `$${placed.body.position.marginUsd}; account equity ${placed.body.account.equity}, free margin ${placed.body.account.freeMargin}`);
  check(placed.status === 201 && placed.body.position.status === 'PENDING', 'the order is PENDING until the next minute');
  await c.ack('setTimeframe', { timeframe: '5m' });
  await c.ack('setSpeed', { speedMs: 500 });
  const from = c.events.length;
  await c.ack('play');
  let closed: Position | undefined;
  let filled: Position | undefined;
  for (const until = Date.now() + 120_000; !closed && Date.now() < until; await sleep(50)) {
    for (const e of c.events.slice(from).filter((x) => x.event === 'positions')) {
      for (const p of e.payload as Position[]) {
        if (p.id !== placed.body.position.id) continue;
        if (p.status === 'OPEN' && !filled) filled = p;
        if (p.status === 'CLOSED') closed = p;
      }
    }
  }
  await c.ack('pause');
  if (!filled || !closed) throw new Error('the order did not fill and close within 120 s of play');
  const barsPlayed = c.events.slice(from).filter((e) => e.event === 'bar').length;
  log(`Filled at ${filled.entryTime} at ${filled.entryPrice} (the ask open of the minute after the order); closed by ` +
    `${closed.exitReason} at ${closed.exitTime} at ${closed.exitPrice}, after ${barsPlayed} 5m bars at 500 ms; realized ` +
    `$${closed.realizedPnlUsd}`);
  const toPoints = (p: string) => Number(p.replace('.', ''));
  const points = toPoints(closed.exitPrice as string) - toPoints(filled.entryPrice as string);
  const netCents = Math.round((points - 14) * closed.units / 1e5 * 100);
  log(`Recomputed: (${toPoints(closed.exitPrice as string)} - ${toPoints(filled.entryPrice as string)} - 14 commission) points ` +
    `x ${closed.units} / 10^5 = $${(netCents / 100).toFixed(2)}`);
  check(Date.parse(filled.entryTime as string) > Date.parse(placed.body.position.placedAt), 'filled after the minute it was placed at');
  check(['SL', 'TP'].includes(closed.exitReason as string), `closed by ${closed.exitReason}`);
  const level = closed.exitReason === 'SL' ? sl : tp;
  check(Number(closed.exitPrice) === level || (closed.exitReason === 'SL' ? Number(closed.exitPrice) < sl : Number(closed.exitPrice) > tp),
    `exit at the level ${level.toFixed(5)} (or beyond it on a gap): ${closed.exitPrice}`);
  check(netCents === Math.round(Number(closed.realizedPnlUsd) * 100), `realized $${closed.realizedPnlUsd} equals the recomputation`);
  const afterClose = await rest<Session>('GET', '/sessions/active');
  check(afterClose.body.balance === (10000 + netCents / 100).toFixed(2), `balance ${afterClose.body.balance} = 10000.00 + realized`);
  log('');

  log('## 4. Disconnect while playing, reconnect');
  await c.ack('play');
  await sleep(1_200);
  await new Promise<void>((r) => { c.socket.once('disconnect', () => r()); c.socket.disconnect(); });
  await sleep(500);
  const afterDisconnect = await rest<Session>('GET', '/sessions/active');
  await sleep(2_000);
  const later = await rest<Session>('GET', '/sessions/active');
  log(`After the last socket left: ${afterDisconnect.body.status}, clock ${afterDisconnect.body.clockTime}; 2 s later ` +
    `${later.body.status}, clock ${later.body.clockTime}`);
  check(afterDisconnect.body.status === 'PAUSED' && later.body.clockTime === afterDisconnect.body.clockTime, 'paused and saved on disconnect');
  c = await connect();
  await sleep(2_000);
  const barsAfterReconnect = c.events.filter((e) => e.event === 'bar').length;
  log(`Reconnected: state ${c.state.session.status} at ${c.state.session.clockTime}; bars in the next 2 s: ${barsAfterReconnect}`);
  check(c.state.session.status === 'PAUSED' && barsAfterReconnect === 0, 'a reconnect is PAUSED and nothing plays');
  log('');

  log('## 5. End the session');
  const ended = await rest<Ended>('POST', `/sessions/${created.body.id}/end`);
  await sleep(300);
  log(`POST /end: HTTP ${ended.status}, ${ended.body.session.status}, balance ${ended.body.session.balance}, ` +
    `${ended.body.closed.length} closed and ${ended.body.cancelled.length} cancelled at the end; socket got 'ended': ` +
    `${c.events.some((e) => e.event === 'ended')}`);
  check(ended.status === 200 && ended.body.session.status === 'ENDED', 'ended');
  check((await rest<Session>('GET', '/sessions/active')).status === 404, 'no active session afterwards');
  c.socket.disconnect();
  log('');
  log(failures.length === 0 ? '**Result: all checks pass.**' : `**Result: ${failures.length} check(s) failed.**`);

  writeFileSync(reportPath, lines.join('\n') + '\n');
  console.log(`report: ${reportPath}`);
  process.exit(failures.length === 0 ? 0 : 1);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
