"""Checks that the running service's /predictions equal the offline walk-forward run for
one test month per pair, over HTTP, and writes docs/validation/ml-inference-parity.md.
Fails on any difference above 1e-6, a different sample set, or an empty month.

    python -m ml_service.parity --url http://localhost:3006

The access token is minted with the shared JWT_ACCESS_SECRET in auth-service's format,
so no database user is created.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import time
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

import jwt
import numpy as np

from ml_service.auth import ACCESS_TOKEN_CLAIMS, access_secret
from ml_service.config import REPO_ROOT, SERVICE_ROOT

MONTHS = {
    "EUR_USD": ("2022-03-01", "2022-03-31"),
    "GBP_USD": ("2019-06-01", "2019-06-30"),
    "USD_JPY": ("2020-03-01", "2020-03-31"),
    "XAU_USD": ("2017-10-01", "2017-10-31"),
}
TOLERANCE = 1e-6


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", default="http://localhost:3006")
    parser.add_argument("--doc", type=Path, default=REPO_ROOT / "docs" / "validation" / "ml-inference-parity.md")
    args = parser.parse_args()
    now = int(time.time())
    tok = jwt.encode(
        {
            **ACCESS_TOKEN_CLAIMS,
            "sub": "aaaaaaaa-0000-4000-8000-000000000001",
            "email": "parity@example.com",
            "role": "TRADER",
            "iat": now,
            "exp": now + 900,
        },
        access_secret(),
        algorithm="HS256",
    )
    rows, failures = [], []
    for instrument, (start, end) in MONTHS.items():
        req = urllib.request.Request(
            f"{args.url}/api/ml/predictions/{instrument}?from={start}&to={end}",
            headers={"Authorization": f"Bearer {tok}"},
        )
        with urllib.request.urlopen(req, timeout=120) as r:
            body = json.load(r)
        year = int(start[:4])
        offline = np.load(SERVICE_ROOT / "models" / f"{instrument.replace('_', '')}-1h-test{year}-test.npz")
        lo = int(datetime.fromisoformat(start).replace(tzinfo=UTC).timestamp())
        hi = int(datetime.fromisoformat(end).replace(tzinfo=UTC).timestamp()) + 86400
        month = (offline["target_time"] >= lo) & (offline["target_time"] < hi)
        expected = dict(zip(offline["target_time"][month].tolist(), offline["p_lstm"][month].tolist(), strict=True))
        served = {
            int(datetime.fromisoformat(p["targetBarTime"].replace("Z", "+00:00")).timestamp()): p
            for p in body["predictions"]
            if p["scored"]
        }
        same_set = served.keys() == expected.keys() and len(expected) > 0
        diffs = [abs(served[t]["pUp"] - p) for t, p in expected.items() if t in served]
        max_diff = max(diffs) if diffs else float("nan")
        same_class = all(
            served[t]["predicted"] == ("UP" if p >= 0.5 else "DOWN") for t, p in expected.items() if t in served
        )
        ok = same_set and max_diff <= TOLERANCE and same_class
        rows.append(
            f"| {instrument.replace('_', '/')} | {start} .. {end} | {len(body['predictions'])} | {len(expected)} | "
            f"{len(served)} | {'yes' if same_set else '**no**'} | {max_diff:.2e} | "
            f"{'yes' if same_class else '**no**'} | "
            f"{'**match**' if ok else '**DIFFERS**'} |"
        )
        if not ok:
            failures.append(instrument)
    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True, cwd=REPO_ROOT
    ).stdout.strip()
    doc = [
        "# ML inference parity (step 4)",
        "",
        f"Generated by `python -m ml_service.parity` on {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')} at commit"
        f" `{commit}`, against the running service ({args.url}).",
        "",
        "For one test month per pair, `GET /api/ml/predictions/{instrument}` (computed live from the database with the",
        "fold model whose test year contains each bar) is compared with the offline walk-forward predictions",
        f"(`models/*-test.npz`): the same scored samples, every probability within {TOLERANCE:g}, "
        "the same predicted class.",
        "",
        "| Pair | Month | Served bars | Offline samples | Served scored | Same samples | Max abs. difference "
        "| Same class | Result |",
        "|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "Served bars include target bars without a score (flat, or under 30 minutes), marked `scored: false`.",
        "",
    ]
    args.doc.write_text("\n".join(doc), encoding="utf-8")
    print("\n".join(rows))
    if failures:
        raise SystemExit(f"parity FAILED for {failures}")


if __name__ == "__main__":
    main()
